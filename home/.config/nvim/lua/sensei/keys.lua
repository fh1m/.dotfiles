local function launcher(args)
  local host = vim.env.SENSEI_HOST_HOME or vim.fn.expand('~')
  local command = { host .. '/.local/bin/sensei-dev' }
  vim.list_extend(command, args)
  vim.system(command, { text = true }, function(r)
    vim.schedule(function() if r.code ~= 0 then vim.notify(r.stderr or r.stdout or 'Launcher failed', vim.log.levels.ERROR) end end)
  end)
end
key('<leader>pp', function()
  local host = vim.env.SENSEI_HOST_HOME or vim.fn.expand('~')
  if vim.env.TMUX then
    vim.system({ 'tmux', 'display-popup', '-E', '-w', '80%', '-h', '75%', host .. '/.local/bin/sensei-project-picker' })
  else
    vim.notify('Run sensei-dev open PATH or use your terminal project picker.')
  end
end, 'Saved projects')
