vim.api.nvim_create_user_command('DevVaultsReload', function()
  if not package.loaded.obsidian then require('lazy').load({ plugins = { 'obsidian.nvim' } }) end
  local specs = require('sensei.knowledge').config().vaults or {}
  if #specs > 0 then require('obsidian.workspace').setup(specs) end
  vim.notify(('Discovered %d vaults'):format(#specs))
end, { desc = 'Discover newly registered Obsidian vaults without restarting' })
