key('<leader>ay', function()
  local start, finish = require('sensei.knowledge').capture_range()
  local p = require('sensei.environment').profile()
  local text = ('Project: %s\nEnvironment: %s\nFile: %s:%d-%d\n\n%s'):format(p.root, require('sensei.environment').label(), vim.api.nvim_buf_get_name(0), start, finish,
    table.concat(vim.api.nvim_buf_get_lines(0, start - 1, finish, false), '\n'))
  vim.fn.setreg('+', text)
  vim.notify('Context copied; paste it into the agent when ready.')
end, 'Copy context (never submit)', { 'n', 'x' })
